"""Offline golden-vector generation only; tests and runtime do not import this.

Run with CPU-only PyTorch and the prior verified tools/qtip_ref.py; its
verify_source() checks Cornell's pinned source before any import of that code.
The deterministic bytes are legal cyclic trellis streams (not model weights).
"""

import argparse
import importlib.util
from pathlib import Path

import torch


def generate(ref, source):
    torch.set_num_threads(1)
    torch.compiler.set_stance("force_eager")
    torch.load = ref.forbidden
    qtip = ref.load_qtip(ref.verify_source(source))
    rows = [(mode, L, K, V, Q, False) for mode, L, V, Q in ref.ROWS for K in range(1, 5)]
    rows += [("quantlut_sym", 16, K, 2, 9, True) for K in (2, 3, 4)]
    print("// Generated by qtip_oracle.py against Cornell QTIP " + ref.PIN)
    print("static constexpr Golden vectors[] = {")
    for index, (mode, L, K, V, Q, swizzled) in enumerate(rows):
        m, n = (32, 64) if K % 2 else (64, 32)
        seed = (0x51444950 + index) & 0xffffffff
        values = []
        for _ in range(m * n * K // 8):
            seed = (seed * 1664525 + 1013904223) & 0xffffffff
            values.append(seed >> 24)
        packed = torch.tensor(values, dtype=torch.uint8).view(torch.int16).reshape(-1, 16 * K)
        tlut = (((torch.arange((1 << Q) * V) * 149) % 253 - 126) / 128).half().reshape(-1, V) if Q else None
        reader = qtip.bitshift.BitshiftLinear(16, 16, L, K, V, Q, mode, tlut=tlut, has_kernel=swizzled)
        if swizzled:
            decoded = reader.get_hatW_kernel(packed, m, n)
        else:
            decoded = reader.get_hatW(reader.cb.unpack_trellis(packed, 256), m, n)
        su = ((torch.arange(n) * 5 % 31) - 15) / 16
        sv = ((torch.arange(m) * 7 % 29) - 14) / 16
        x = ((torch.arange(n) * 11 % 53) - 26) / 32
        hin = qtip.had.matmul_hadU(torch.eye(n))
        hout = qtip.had.matmul_hadU(torch.eye(m))
        y = (hout @ decoded.float() @ hin @ (su * x)) * sv * 0.375
        mode_id = {"1mad": "mad1", "2mad": "mad2", "3inst": "inst3"}.get(mode, mode)
        layout_id = "cuda_swizzled" if swizzled else "reference"
        print(f"    {{{{{m}, {n}, {L}, {K}, {V}, {Q}, Mode::{mode_id}, Layout::{layout_id}}}, {{")
        for chunk in y.split(8):
            print("        " + ", ".join(f"{float(f):.9e}f" for f in chunk) + ",")
        print("    }},")
    print("};")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("probe", type=Path, help="prior verified tools/qtip_ref.py")
    parser.add_argument("source", type=Path, help="matching local Cornell source tree")
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location("brewery_qtip_ref", args.probe)
    ref = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ref)
    generate(ref, args.source)


if __name__ == "__main__":
    main()
