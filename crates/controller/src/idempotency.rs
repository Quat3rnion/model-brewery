use rusqlite::{Connection, OptionalExtension as _, Transaction, params};
use serde::Serialize;
use sha2::{Digest as _, Sha256};

pub struct Submission<'a> {
    scope: &'static str,
    key: &'a str,
    fingerprint: [u8; 32],
}

pub enum Replay {
    New,
    Matched(String),
    Conflict,
}

pub fn valid_key(key: &str) -> bool {
    (1..=128).contains(&key.len())
        && key
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'))
}

pub fn install(conn: &Connection) -> rusqlite::Result<()> {
    // No foreign key to resources: deletion must not release a committed key.
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS idempotent_submissions(
           scope TEXT NOT NULL, key TEXT NOT NULL, fingerprint BLOB NOT NULL,
           resource_id TEXT NOT NULL, PRIMARY KEY(scope, key)
         );",
    )
}

impl<'a> Submission<'a> {
    pub fn new(
        scope: &'static str,
        key: &'a str,
        request: &impl Serialize,
    ) -> serde_json::Result<Self> {
        Ok(Self {
            scope,
            key,
            fingerprint: fingerprint(request)?,
        })
    }

    pub fn lookup(&self, conn: &Connection) -> rusqlite::Result<Replay> {
        let prior: Option<(Vec<u8>, String)> = conn
            .query_row(
                "SELECT fingerprint, resource_id FROM idempotent_submissions WHERE scope=? AND key=?",
                params![self.scope, self.key],
                |row| Ok((row.get(0)?, row.get(1)?)),
            )
            .optional()?;
        Ok(match prior {
            None => Replay::New,
            Some((fingerprint, id)) if fingerprint == self.fingerprint => Replay::Matched(id),
            Some(_) => Replay::Conflict,
        })
    }
}

pub fn fingerprint(request: &impl Serialize) -> serde_json::Result<[u8; 32]> {
    // Hash the typed input, not request bytes or fields generated by the server.
    let mut canonical = serde_json::to_value(request)?;
    canonical.sort_all_objects();
    Ok(Sha256::digest(serde_json::to_vec(&canonical)?).into())
}

pub fn record(
    tx: &Transaction<'_>,
    submission: Option<&Submission<'_>>,
    id: &str,
) -> rusqlite::Result<()> {
    if let Some(submission) = submission {
        tx.execute(
            "INSERT INTO idempotent_submissions(scope, key, fingerprint, resource_id) VALUES (?, ?, ?, ?)",
            params![submission.scope, submission.key, &submission.fingerprint[..], id],
        )?;
    }
    Ok(())
}
